          <li>Approve the annual police service budget and monitor expenditure across operational units.</li>
          <li>Oversee high-level investigations, transnational crime responses, and major security operations.</li>
          <li>Approve statutory administrative actions, including penalty notice reviews and orders regarding forfeited property.</li>
          <li>Coordinate with international law enforcement partners, regional security networks, and foreign diplomatic missions.</li>
          <li>Review disciplinary proceedings and make final administrative determinations for lower-ranking officers.</li>
