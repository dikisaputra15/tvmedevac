          <li>Issue move-on directions and manage public order during gatherings, demonstrations, or public events.</li>
          <li>Manage outer island police posts and coordinate daily operational reporting with the headquarters.</li>
          <li>Execute court warrants, serve summonses, and issue notices to appear in court.</li>
          <li>Secure minor crime scenes and preserve physical evidence before specialist arrival.</li>
          <li>Participate in community outreach initiatives and collaborate with local island councils (<em>Kaupule</em>).</li>
          <li>Arrest suspects caught committing offences or operating in breach of bail conditions.</li>
